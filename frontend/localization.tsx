const translationCache = new Map<string, string>();

type DevElementStore = { _store?: { validated?: number } };

const carryValidationFlag = (source: ReactNode, clone: ReactNode): ReactNode => {
  const from = (source as DevElementStore)?._store;
  const to = (clone as DevElementStore)?._store;
  if (from && to) to.validated = from.validated;
  return clone;
};

export function translateText(text: string, language: AppLanguage): string {
  if (language !== 'HI') return text;
  const cached = translationCache.get(text);
  if (cached !== undefined) return cached;
  let result = text;
  const match = text.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (match) {
    const [, leading, content, trailing] = match;
    const translated = hindiTranslations[content.replace(/\s+/g, ' ')];
    if (translated) result = `${leading}${translated}${trailing}`;
  }
  translationCache.set(text, result);
  return result;
}

function localizeNode(node: ReactNode, language: AppLanguage): ReactNode {
  if (typeof node === 'string') return translateText(node, language);
  if (Array.isArray(node)) {
    let changed = false;
    const next = node.map(child => {
      const localized = localizeNode(child, language);
      if (localized !== child) changed = true;
      return localized;
    });
    return changed ? next : node;
  }
  if (!isValidElement<{ children?: ReactNode; title?: string; placeholder?: string; subtitle?: string; alt?: string; 'aria-label'?: string }>(node)) return node;

  const props = node.props;
  const localizedProps: Record<string, unknown> = {};
  let changed = false;
  if (props.children !== undefined) {
    const children = localizeNode(props.children, language);
    if (children !== props.children) {
      localizedProps.children = children;
      changed = true;
    }
  }
  for (const attribute of ['title', 'placeholder', 'aria-label', 'alt', 'subtitle'] as const) {
    if (typeof props[attribute] === 'string') {
      const translated = translateText(props[attribute], language);
      if (translated !== props[attribute]) {
        localizedProps[attribute] = translated;
        changed = true;
      }
    }
  }
  return changed ? carryValidationFlag(node, cloneElement(node, localizedProps)) : node;
}

export function LocalizedTree({ language, children }: { language: AppLanguage; children: ReactNode }) {
  if (language !== 'HI') return <>{children}</>;
  return <>{localizeNode(children, language)}</>;
}
